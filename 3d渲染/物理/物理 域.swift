import Foundation

// MARK: - 全局物理
//
// 口径：
// - 这里只放「全局单体」的力：重力、风、流（方向场）、湍流、阻力。
//   它跟摄像机一样属于全局单例，不是场景对象、不上大纲、不进集合；
//   每个发射器再按自己的 `重力倍率` / `风力倍率` 决定吃多少（见 特效设置）。
// - 落盘跟视口设置一起走工程快照，随工程走而不随 App 走；
// - 视口层（MTK）按它现算，路径追踪出图暂不参与。

struct 物理域: Codable, Equatable, Sendable {
    /// 总开关：关掉后所有力归零，粒子只剩初速（方便单独看发射形状）
    var 启用: Bool = true

    /// 重力加速度（米/秒²，世界坐标）。默认地球：Y 轴 -9.81
    var 重力: Vec3 = Vec3(0, -9.81, 0)

    /// 恒定风场（米/秒，世界坐标）
    var 风: Vec3 = .zero

    /// 流场方向（世界坐标，长度即强度，米/秒）：烟/火的上升气流用它，跟风叠加
    var 流: Vec3 = .zero

    /// 湍流强度（0…1）：把风/流打碎成随时间变化的小尺度扰动
    var 湍流: Double = 0.0

    /// 空气阻力系数（0…1，每秒衰减比例）
    var 阻力: Double = 0.1

    /// 时间缩放：1 = 实时，0.25 = 慢动作（调参时用）
    var 时间缩放: Double = 1.0

    static let 标准 = 物理域()

    /// 是否一条力都没开（菜单上用来标「无」）
    var 是静止: Bool {
        !启用 || (重力 == .zero && 风 == .zero && 流 == .zero && 湍流 <= 0)
    }
}

/// 「全局物理」菜单里的一项：点一下就把整套力换成这一档
struct 物理预设: Identifiable, Equatable, Sendable {
    let id: String
    let 名称: String
    let 符号: String
    let 域: 物理域

    static func == (甲: 物理预设, 乙: 物理预设) -> Bool { 甲.id == 乙.id }
}

enum 物理库 {

    /// 出厂档位：环境档（地球 / 无重力 / 水下）+ 风档（微风 / 强风 / 上升气流 / 涡流）
    static var 预设们: [物理预设] {
        [
            物理预设(id: "env.地球", 名称: "地球重力", 符号: "globe", 域: {
                var d = 物理域.标准
                d.阻力 = 0.08
                return d
            }()),

            物理预设(id: "env.零重力", 名称: "零重力", 符号: "moon.stars.fill", 域: {
                var d = 物理域.标准
                d.重力 = .zero
                d.阻力 = 0.0
                return d
            }()),

            物理预设(id: "env.水下", 名称: "水下（慢 + 大阻力）", 符号: "water.waves", 域: {
                var d = 物理域.标准
                d.重力 = Vec3(0, -1.6, 0)
                d.阻力 = 0.85
                d.时间缩放 = 0.6
                return d
            }()),

            物理预设(id: "wind.微风", 名称: "微风", 符号: "wind", 域: {
                var d = 物理域.标准
                d.风 = Vec3(0.8, 0, 0.3)
                d.湍流 = 0.15
                return d
            }()),

            物理预设(id: "wind.强风", 名称: "强风", 符号: "wind.snow", 域: {
                var d = 物理域.标准
                d.风 = Vec3(6.0, 0, 1.2)
                d.湍流 = 0.45
                d.阻力 = 0.12
                return d
            }()),

            物理预设(id: "flow.上升气流", 名称: "上升气流", 符号: "arrow.up.circle.fill", 域: {
                var d = 物理域.标准
                d.流 = Vec3(0, 2.4, 0)
                d.湍流 = 0.35
                return d
            }()),

            物理预设(id: "flow.涡流", 名称: "涡流（绕 Y 旋）", 符号: "tornado", 域: {
                var d = 物理域.标准
                d.流 = Vec3(0, 0.6, 0)
                d.风 = Vec3(2.2, 0, 0)
                d.湍流 = 0.7
                return d
            }()),
        ]
    }

    /// 反查「当前是哪一档」：菜单上打勾用；对不上就返回 nil（用户手调过参数）
    static func 匹配(_ 域: 物理域) -> 物理预设? {
        预设们.first { $0.域 == 域 }
    }
}
