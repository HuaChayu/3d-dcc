import Foundation
import simd

// MARK: - 灯源取值（消费端唯一可见的灯形态）

/// 一盏灯在消费端的样子：参数、位置、朝向全部来自数据层快照，消费端不再回头读场景模型。
struct 灯源取值 {
    var 外部键: String
    var 名称: String
    var 设置: 灯光设置
    /// 位置（模型口径）：写入方交给变换域的唯一形态 —— 交的是 TRS，不是算好的矩阵。
    var 位置: Vec3
    /// 朝向（欧拉角，度）：与模型 `object.rotation` 同口径，供朝向四元数使用。
    var 朝向: Vec3
    /// 缩放（模型口径）
    var 缩放: Vec3
    /// 世界矩阵：**由变换域派生后回填**，只有 `取灯源(快照)` 出来的灯源才带真值。
    /// 写入方交给 `同步()` 时这里是单位阵，杜绝"自己先乘一遍再交上去"的老路。
    var 世界矩阵: simd_double4x4
}

// MARK: - 灯光接线

/// 灯光接线：场景模型里"灯"进入数据层的唯一入口（规矩 1），
/// 消费端一律经 `场景快照.灯光` / `场景快照.变换` 的只读视图取值（规矩 2）。
///
/// 它同时是灯段版本号的唯一记账方：只有它知道"这次写入到底改没改值"，
/// 所以订阅者比的是两个单调版本号，而不是对整场景做哈希。
final class 灯光接线 {

    static let 共享 = 灯光接线()

    private let 层 = 场景数据层.共享
    /// 灯的矩阵全部经变换接线进变换域：灯与物体共用同一套记录 / 缓存 / 版本。
    private let 变换 = 变换接线.共享
    /// 键 → 灯标识 / 上次写入取值 / 逐键参数版本：三张表统一在 `域模版` 里。
    /// 灯光原先单线程写入、不持锁；套上模版后仍持一把自己的锁实例，串行性只增不减。
    private let 簿 = 域模版<灯光域标签, 灯源取值>(锁: NSLock())

    /// 本轮同步进来的键序：决定灯缓冲 / 灯 CDF 的排列顺序（必须与模型里的灯顺序一致，
    /// 否则 NEE 的抽样序变了，画面就不再逐像素等价）。真身在 `簿`。
    var 当前键序: [String] { 簿.键序快照() }
    var 当前键集: Set<String> { 簿.键集快照() }

    /// 灯参数版本：功率 / 色温 / 宽高 / 半径 / 锥角 / 柔和 / 朝向 / 启用 / 名称 变了才自增。
    /// 真身是 `簿.内容版本`（只在参数真变 / 新增 / 删除时推进），这里只转发。
    var 参数版本: UInt64 { 簿.内容版本 }
    /// 灯变换版本：**由变换域派生**，不再自己数矩阵变化。
    /// 口径：`变换接线.段版本(当前灯键序)` 一变就自增一次（封包成单调计数，方便日志间比较）。
    /// 也就是说灯的变换版本与物体的变换版本同源（同一批变换记录），只是取了自己那一段的和。
    private(set) var 变换版本: UInt64 = 0
    private var 上次灯变换段版本: UInt64 = .max

    private init() {}

    // MARK: 写入（唯一写入方）

    /// 把模型里的灯同步进数据层，返回"带灯光记账"的快照。
    /// - Parameter 灯列表: 已被消费端按"可见 + 启用"筛过的灯（顺序即模型顺序）。
    @discardableResult
    func 同步(_ 灯列表: [灯源取值]) -> 场景快照 {
        var 新键序: [String] = []
        新键序.reserveCapacity(灯列表.count)

        for 灯 in 灯列表 {
            新键序.append(灯.外部键)

            let 旧id = 簿.标识(键: 灯.外部键)
            var 灯id = 旧id
            var 版本该推进 = false

            // 影响成像的参数：功率 / 色温 / 宽高 / 半径 / 锥角 / 柔和 / 朝向。
            // 名称不参与渲染，单独判，且不推进版本。
            let 参数变了: (灯光记录) -> Bool = { 旧 in
                旧.设置 != 灯.设置 || Vec3(旧.朝向.x, 旧.朝向.y, 旧.朝向.z) != 灯.朝向
            }

            if let 旧id {
                // —— 参数段：只写真的变了的记录
                if let 旧 = 层.灯光.取(旧id),
                    参数变了(旧) || 旧.名称 != 灯.名称
                {
                    _ = 层.灯光.改(旧id, 令牌: .灯光) { 记录 in
                        记录.名称 = 灯.名称
                        记录.设置 = 灯.设置
                        记录.朝向 = SIMD3<Double>(灯.朝向.x, 灯.朝向.y, 灯.朝向.z)
                    }
                    // 【名称不参与渲染】只改名不进 lightsBuffer / 灯 CDF / 灯树，不该推进参数版本：
                    // 推进了等于让消费端白清一次累积、白刷一遍灯缓冲（预览与出图两条路径都白干）。
                    // 口径与几何/材质签名一致：只有真正影响成像的字段才推进版本。
                    版本该推进 = 参数变了(旧)
                }
                // —— 变换段：只把 TRS 交给变换接线，矩阵换算与缓存全在变换域内完成。
                // 值没变时 同步() 不写域、不推版本（拖静止帧不打空转）。
                _ = 变换.同步(
                    键: 灯.外部键,
                    名称: 灯.名称,
                    变换接线.TRS(
                        位置: SIMD3<Double>(灯.位置.x, 灯.位置.y, 灯.位置.z),
                        欧拉角: SIMD3<Double>(灯.朝向.x, 灯.朝向.y, 灯.朝向.z),
                        缩放: SIMD3<Double>(灯.缩放.x, 灯.缩放.y, 灯.缩放.z)
                    )
                )
            } else {
                let 记录 = 灯光记录(
                    名称: 灯.名称,
                    设置: 灯.设置,
                    朝向: SIMD3<Double>(灯.朝向.x, 灯.朝向.y, 灯.朝向.z),
                    外部键: 灯.外部键
                )
                if let 新灯id = 层.灯光.新增(记录, 令牌: .灯光) {
                    灯id = 新灯id
                    版本该推进 = true
                    _ = 变换.同步(
                        键: 灯.外部键,
                        名称: 灯.名称,
                        变换接线.TRS(
                            位置: SIMD3<Double>(灯.位置.x, 灯.位置.y, 灯.位置.z),
                            欧拉角: SIMD3<Double>(灯.朝向.x, 灯.朝向.y, 灯.朝向.z),
                            缩放: SIMD3<Double>(灯.缩放.x, 灯.缩放.y, 灯.缩放.z)
                        )
                    )
                }
            }

            簿.记入(键: 灯.外部键, 标识: 灯id, 值: 灯, 版本该推进: 版本该推进)
        }

        // —— 灯被删/被隐藏：登记删除（物理回收交给引用计数轮询，规矩 5）
        // 变换记录走"删映射 + 留记录"：变换域不提供请求删除（它管父子关系），
        // 留着孤儿记录的代价是一条矩阵，远小于为灯偷偷开一个删除通道。
        let 消失的键 = 簿.收尾(键序: 新键序)
        if !消失的键.isEmpty {
            for 键 in 消失的键 {
                if let 灯id = 簿.移除(键: 键) {
                    _ = 层.灯光.请求删除(灯id, 令牌: .灯光)
                }
            }
            簿.推进内容版本()
        }

        // 把"这一批是灯"告诉变换接线：灯矩阵与非灯对象矩阵在同一张域里，
        // 只有分得清谁是谁，才能各自记一个单调版本号（拖灯不推进对象变换版本）。
        变换.登记灯键(簿.键集快照())

        // —— 灯变换版本：由变换域的"灯段版本"封包成单调计数。
        // 灯被删时和会变小，因此不能直接拿和当版本号；这里只取"变没变"这一个信息。
        let 段版本 = 变换.段版本(键们: 新键序)
        if 段版本 != 上次灯变换段版本 {
            上次灯变换段版本 = 段版本
            变换版本 &+= 1
        }

        var 快照 = 层.生成快照()
        快照.灯光记账 = 灯光版本记账(参数: 参数版本, 变换: 变换版本)
        return 快照
    }

    // MARK: 读取（只经快照只读视图）

    /// 从快照读出灯源（顺序 = 同步进来的模型顺序）。
    /// 只持有只读视图：这里拿不到任何写入口，规矩 2 由类型系统兜住。
    func 取灯源(_ 快照: 场景快照) -> [灯源取值] {
        let 键序 = 簿.键序快照()
        let 键集 = 簿.键集快照()
        var 结果: [灯源取值] = []
        结果.reserveCapacity(键序.count)
        for 键 in 键序 {
            guard 键集.contains(键),
                let 灯id = 簿.标识(键: 键),
                let 记录 = 快照.灯光.取(灯id),
                let 变换id = 变换.变换标识(键: 键),
                let 世界 = 快照.变换.世界矩阵(变换id)
            else { continue }
            结果.append(
                灯源取值(
                    外部键: 记录.外部键,
                    名称: 记录.名称,
                    设置: 记录.设置,
                    位置: Vec3(世界.columns.3.x, 世界.columns.3.y, 世界.columns.3.z),
                    朝向: Vec3(记录.朝向.x, 记录.朝向.y, 记录.朝向.z),
                    缩放: Vec3(1, 1, 1),
                    世界矩阵: 世界
                )
            )
        }
        return 结果
    }

    /// 单盏灯的当前参数（视口灯符号等"按对象取设置"的消费端用）。
    /// - Returns: 没有登记过就是 nil，调用方自行决定回落到模型（第一次构建那一帧）。
    func 取设置(键: String) -> 灯光设置? {
        guard let 灯id = 簿.标识(键: 键) else { return nil }
        return 层.灯光.取(灯id)?.设置
    }

    /// 当前灯的盏数（诊断用）。
    var 盏数: Int { 簿.键集快照().count }
}
