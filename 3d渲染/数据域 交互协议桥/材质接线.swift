import Foundation
import CoreGraphics

// MARK: - 结果类型（调用方必须处理，不许静默当成功）

/// 一次绑定变化的结果
enum 材质绑定结果: Equatable {
    case 变更(旧: UUID?, 新: UUID?)
    case 无需变更
    case 未知材质(UUID)
    case 引用计数错乱(String)
}

/// 删除结果：**有引用一律拒绝**，绝不"先删了再重建一个"。
enum 材质删除结果: Equatable {
    case 已受理
    case 拒绝仍有引用(引用者: [UUID])
    case 未知材质
}

/// 一张导入源图的记账：原始字节 + 显式持有者。
/// 持有者不是材质本身，而是「谁在替这张图担保」：导入它的材质 id、正在编辑它的工程等。
/// 节点里的 image 引用另算 —— 那个直接数节点图，不在这里存。
struct 源图账 {
    var 字节: Data?
    var 持有者: Set<UUID> = []
}

// MARK: - 材质接线

/// 材质接线：模型里"材质"进入数据层的**唯一入口**（规矩 1）。
///
/// 消费端（视口、路径追踪、检查器、资源库、材质球库）一律经 `场景快照.材质` 只读视图取材质，
/// 拿不到任何写入口 —— 规矩 2 由类型系统兜住，不靠自觉。
///
/// 它一个人负责三件事：
/// 1. 长期引用键（MaterialAsset.id）→ 域内标识 的索引。每帧每对象都要反查，必须 O(1)。
/// 2. 对象 → 槽位表 的正向索引，**材质的引用计数与引用者一律从它派生**（唯一口径，见下）。
/// 3. 材质 → 引用它的对象集合的反向索引，是上面槽位表的派生投影，供删除拒绝与界面查询。
///
/// 【引用计数唯一口径】真值 = 对象实际引用的全部材质槽位（0 号槽 + 各副槽），
/// 由 `正向索引` 里的槽位表逐槽派生，接线与域都不另存计数器：
/// - `引用计数(资产:)` = 槽位表里该材质出现的**槽位数**（同一对象占两个槽就算两处引用）；
/// - `引用者(资产:)` = 引用到它的**对象集合**（Set，按对象去重）。
/// 域槽上的 `引用计数` 是通用域机制，材质域**不再使用**（不再调增引用/减引用），
/// 这样"还有没有人用"只有一条路径可回答，不会出现两套计数器打架。
///
/// 【删除与回收】仍有引用 → 拒绝并记录（写进 `拒绝删除记录`，界面照实提示）；
/// 无引用 → 交域走 `请求延迟删除`（不做"计数为 0 就当场释放"的快路径），
/// 槽真正释放的唯一时机是 `尝试回收()`：帧末（GPU 命令缓冲全部完成）且无引用才放。
final class 材质接线 {
    static let 共享 = 材质接线()

    private let 层 = 场景数据层.共享

    /// 长期引用键 → 域内标识
    private var 索引: [UUID: 稳定标识<材质域标签>] = [:]
    /// 对象 → 材质槽位表（下标 = 槽序，0 号槽是主槽；nil = 该槽为空）
    private var 正向索引: [UUID: [稳定标识<材质域标签>?]] = [:]
    /// 材质 → 引用它的对象集合（槽位表的派生投影，按对象去重）
    private var 反向索引: [稳定标识<材质域标签>: Set<UUID>] = [:]
    /// 被拒的删除（诊断 + 界面提示），绝不静默吞掉
    private(set) var 拒绝删除记录: [(材质: UUID, 引用者: Int)] = []
    /// 还在 GPU 上的帧数（提交 +1，命令缓冲完成回主线程 -1）：>0 时一律不回收材质槽。
    /// 提交在渲染线程、完成回调在 GPU 线程、回收在主线程，所以这一个计数单独加锁。
    private let 帧锁 = NSLock()
    private var _在飞帧数 = 0
    var 在飞帧数: Int {
        帧锁.lock()
        defer { 帧锁.unlock() }
        return _在飞帧数
    }

    // MARK: - 源图账本（导入位图的所有权在材质域一侧）

    /// 一张导入源图的记账：原始字节（存档要写）+ 显式持有者（导入方 / 工程）。
    /// 节点里的引用不单独存一份计数：直接数材质节点图的 image 引用，
    /// 两处各记一套必有一天对不上，那种「明明删了却释放不掉」的账最难查。
    private let 源图锁 = NSLock()
    private var 源图账本: [UUID: 源图账] = [:]

    private init() {
        #if DEBUG
        let 结果 = 自检材质域()
        // 用 NSLog 而不是 print：stdout 重定向到文件是块缓冲，进程被杀时整段自检结果会丢失
        NSLog("【材质域自检】%@", 结果.报告.replacingOccurrences(of: "\n", with: " | "))
        NSLog("【材质域自检】结论：%@", 结果.全过 ? "全部数值断言通过" : "有失败项，见上一条")
        // 派生缓存淘汰（引用计数 / 字节上限 / 在飞帧保护）的账面断言：放在域初始化期跑，
        // 那时贴图库还是空的，自检造出来的账可以随跑随清，不会碰到真实贴图。
        视口纹理库.自检派生淘汰()
        #endif
    }

    // MARK: - 读（消费者可用）

    /// 全局域版本：回答"有没有材质动过"
    var 域版本: UInt64 { 层.材质.版本号 }

    /// 单材质版本：回答"动的是哪一个"。没登记返回 nil，调用方按"不存在"处理。
    func 版本(资产 id: UUID) -> UInt64? {
        guard let 标 = 索引[id] else { return nil }
        return 层.材质.取(标)?.参数版本
    }

    /// 按长期引用键取材质。返回的是值语义副本，改它不会回写域。
    func 取(资产 id: UUID) -> MaterialAsset? {
        guard let 标 = 索引[id] else { return nil }
        return 层.材质.取(标)?.资产
    }

    /// 全部材质（顺序 = 域内顺序）。这是**域内全量**，含"已受理删除、槽还没回收"的那批 ——
    /// 只有回收逻辑与自检该用它（它们要看见待回收条目）。界面/存档/导出请走 `在册()`。
    func 全部() -> [(标识: 稳定标识<材质域标签>, 记录: 材质记录)] {
        var 结果: [(标识: 稳定标识<材质域标签>, 记录: 材质记录)] = []
        层.材质.遍历 { 标, 记录 in 结果.append((标, 记录)) }
        return 结果
    }

    /// 在册材质（顺序 = 域内顺序）：**已经对外生效的那批**。
    ///
    /// 删除是延迟的——受理那一刻只摘索引 + 排进待回收队列，槽要等帧末「无在飞帧」才释放，
    /// 在那之前域里一直留着这条记录。UI 若照 `全部()` 取投影，就会继续把已删材质画出来：
    /// 表现正是「删完材质球还赖在页面上，tab 切走再回来才消失」。
    /// 判据用索引：受理删除时索引已经摘了，待回收的那批恰好是"域里有、索引里没有"。
    func 在册() -> [(标识: 稳定标识<材质域标签>, 记录: 材质记录)] {
        let 有效 = Set(索引.values)
        var 结果: [(标识: 稳定标识<材质域标签>, 记录: 材质记录)] = []
        层.材质.遍历 { 标, 记录 in
            guard 有效.contains(标) else { return }
            结果.append((标, 记录))
        }
        return 结果
    }

    /// 一批材质的聚合版本：**只混入**「这组材质各自的单材质版本」，不掺全局域版本。
    ///
    /// 不掺的理由：掺了以后改库里任何一条没人用的材质、或增删一个不相干的材质，
    /// 这批材质的聚合版本都会变，PT 的材质缓冲就白重建一次。
    /// 增删材质导致槽位重排这件事由「这组材质集合本身变了」推进（集合变 → 哈希输入变），
    /// 不需要再借全局域版本号兜底 —— 早先注释写的"另加一次域版本号"与实现不符，已按实现改正。
    /// PT 用这个回答「材质缓冲要不要重传」，视口按单材质版本逐物体判，两者都不再自拼签名。
    func 场景材质版本(_ 资产IDs: [UUID]) -> UInt64 {
        var 混 = Hasher()
        for id in Set(资产IDs).sorted(by: { $0.uuidString < $1.uuidString }) {
            guard let 标 = 索引[id], let 记录 = 层.材质.取(标) else { continue }
            混.combine(id)
            混.combine(记录.参数版本)
        }
        return UInt64(bitPattern: Int64(混.finalize()))
    }

    /// 谁在用这个材质（反向索引，按对象去重）
    func 引用者(资产 id: UUID) -> Set<UUID> {
        guard let 标 = 索引[id] else { return [] }
        return 反向索引[标] ?? []
    }

    /// 引用计数 = 该材质在全部对象槽位表里占的**槽位数**（主槽 + 副槽，逐槽计）。
    /// 例：甲只被某对象的第 1 槽引用 → 1；同一对象的 0/1 两槽都是甲 → 2。
    func 引用计数(资产 id: UUID) -> Int {
        guard let 标 = 索引[id] else { return 0 }
        var 数 = 0
        for 表 in 正向索引.values {
            for 槽 in 表 where 槽 == 标 { 数 += 1 }
        }
        return 数
    }

    /// 对象的主槽材质（0 号槽）。视口与 PT 目前只认主槽，副槽一律从这里之外取。
    func 材质(对象: UUID) -> UUID? {
        guard let 表 = 正向索引[对象], let 主 = 表.first ?? nil else { return nil }
        return 层.材质.取(主)?.资产ID
    }

    /// 对象的完整槽位表（资产 id 版，nil = 空槽）。副槽没接入的消费端也应尊重这张表。
    func 槽位表(对象: UUID) -> [UUID?] {
        guard let 表 = 正向索引[对象] else { return [] }
        return 表.map { 标 in 标.flatMap { 层.材质.取($0)?.资产ID } }
    }

    /// 当前全部绑定（对象 → 主槽材质资产 id），给场景构建与 PT 转译一次性取。
    func 绑定表() -> [UUID: UUID] {
        var 结果: [UUID: UUID] = [:]
        for (对象, 表) in 正向索引 {
            guard let 主 = 表.first ?? nil, let 资产 = 层.材质.取(主)?.资产ID else { continue }
            结果[对象] = 资产
        }
        return 结果
    }

    // MARK: - 写（只此一处，全部带 .材质 令牌）

    /// 登记一个材质（新建）。同一资产 id 重复登记视为调用方 bug，直接拒绝。
    @discardableResult
    func 登记(_ 资产: MaterialAsset) -> Bool {
        guard 索引[资产.id] == nil else {
            架构记录(.重复所有者, "材质 \(资产.name) 重复登记，id=\(资产.id)")
            return false
        }
        let 记录 = 材质记录(资产: 资产, 参数版本: 1, 图像引用: 资产.图像引用表)
        guard let 标 = 层.材质.新增(记录, 令牌: .材质) else {
            架构记录(.非所有者写入, "材质 \(资产.name) 登记被域拒绝")
            return false
        }
        索引[资产.id] = 标
        层.材质.清脏(标)
        return true
    }

    /// 改材质：参数 / 节点图 / 名称 / 副本关系 / 出厂快照的**所有**写入都走这里。
    ///
    /// 写入后统一做三件事：单材质版本 +1、按图重算图像引用、域版本由 `改` 自己推进。
    /// 不再额外"标脏引用者"：消费端判定一律读版本号（见 `场景材质版本`），
    /// 接线里不维护第二套脏标记。
    @discardableResult
    func 改(资产 id: UUID, _ 体: (inout MaterialAsset) -> Void) -> Bool {
        guard let 标 = 索引[id] else {
            架构记录(.未知标识, "改材质找不到 id=\(id)，不许凭空补一条")
            return false
        }
        let 成 = 层.材质.改(标, 令牌: .材质) { 记录 in
            let 旧 = 记录.资产
            体(&记录.资产)
            记录.图像引用 = 记录.资产.图像引用表
            // 口径与灯光/几何一致：只有真正影响成像的改动才推进参数版本。
            // 拖节点位置、改标题这类编辑期写入不推进 —— 否则视口会当成材质变了，
            // PT 场景重译、累积清零，画面一路从 1spp 重来（拖节点时的"视口重算"就是它）。
            if !旧.外观相同(记录.资产) { 记录.参数版本 &+= 1 }
        }
        return 成
    }

    /// 批量改（出厂快照补齐、内置标记这类整库级别的写入）。
    @discardableResult
    func 批量改(_ 体: (inout MaterialAsset) -> Void) -> Int {
        var 数 = 0
        for 标 in 层.材质.全部标识() {
            let 成 = 层.材质.改(标, 令牌: .材质) { 记录 in
                let 旧 = 记录.资产
                体(&记录.资产)
                记录.图像引用 = 记录.资产.图像引用表
                if !旧.外观相同(记录.资产) { 记录.参数版本 &+= 1 }
            }
            if 成 { 数 += 1 }
        }
        return 数
    }

    /// 换绑对象材质（M:N 的核心）：一次给**完整槽位表**，0 号槽是主槽。
    ///
    /// 计数不另做增删：改完槽位表后，`引用计数` 与 `引用者` 都是从新槽位表现算的派生值，
    /// 所以"只被副槽引用"也会被算进去（旧口径只看主槽，会把仍在用的材质判成 0 引用）。
    @discardableResult
    func 绑定(对象: UUID, 槽位表 资产IDs: [UUID?]) -> 材质绑定结果 {
        var 新表: [稳定标识<材质域标签>?] = []
        新表.reserveCapacity(资产IDs.count)
        for 槽 in 资产IDs {
            guard let id = 槽 else { 新表.append(nil); continue }
            guard let 标 = 索引[id] else { return .未知材质(id) }
            新表.append(标)
        }
        // 尾部空槽不占位（前面中段的空槽要留，槽序是语义的一部分）
        while let 尾 = 新表.last, 尾 == nil { 新表.removeLast() }

        let 旧表 = 正向索引[对象] ?? []
        if 旧表 == 新表 { return .无需变更 }

        let 旧资产 = (旧表.first ?? nil).flatMap { 层.材质.取($0)?.资产ID }
        let 新资产 = (新表.first ?? nil).flatMap { 层.材质.取($0)?.资产ID }

        // 反向索引按**对象**做差集（不是按槽次数）：反向索引的语义是"哪些对象引用了该材质"，
        // 同一对象把同一材质从 2 槽减到 1 槽，它依然在引用者里，不能因为"少了一个槽"就被删掉。
        // 槽次数只影响 引用计数（按槽位表派生），不影响反向索引的成员集合。
        let 旧标集 = Set(旧表.compactMap { $0 })
        let 新标集 = Set(新表.compactMap { $0 })
        for 标 in 旧标集.subtracting(新标集) {
            反向索引[标]?.remove(对象)
            if 反向索引[标]?.isEmpty == true { 反向索引[标] = nil }
        }
        for 标 in 新标集.subtracting(旧标集) { 反向索引[标, default: []].insert(对象) }

        正向索引[对象] = 新表.isEmpty ? nil : 新表
        return .变更(旧: 旧资产, 新: 新资产)
    }

    /// 只改主槽（0 号槽）的便利口：副槽整体清空。给"一对象一材质"的旧调用点用。
    @discardableResult
    func 绑定(对象: UUID, 资产 id: UUID?) -> 材质绑定结果 {
        绑定(对象: 对象, 槽位表: id.map { [Optional($0)] } ?? [])
    }

    /// 载入存档 / 新建工程后整表重建绑定。
    /// 表里带的是**完整槽位表**（0 号槽 + 副槽），这样旧档里只被副槽引用的材质不会被误删。
    /// 出现未登记的材质 id 时按"未知材质"记录并跳过该条，不静默补建材质。
    @discardableResult
    func 重建绑定(_ 表: [UUID: [UUID?]]) -> (成: Int, 未知: [UUID]) {
        for 对象 in Array(正向索引.keys) { _ = 解绑(对象: 对象) }
        var 成 = 0
        var 未知: [UUID] = []
        for (对象, 槽位) in 表.sorted(by: { $0.key.uuidString < $1.key.uuidString }) {
            switch 绑定(对象: 对象, 槽位表: 槽位) {
            case .变更, .无需变更: 成 += 1
            case .未知材质(let id): 未知.append(id)
            case .引用计数错乱(let 原因):
                架构记录(.引用计数, "重建绑定时 \(对象) 槽位表登记失败：\(原因)")
                未知.append(contentsOf: 槽位.compactMap { $0 })
            }
        }
        return (成, 未知)
    }

    /// 解绑（对象改回"无材质"）：整个槽位表清空。
    @discardableResult
    func 解绑(对象: UUID) -> 材质绑定结果 { 绑定(对象: 对象, 槽位表: []) }

    /// 删除材质：**仍有引用（含只被副槽引用）时拒绝并记录**，交界面照实提示，绝不静默重建。
    /// 受理后槽不立刻释放，交给 `尝试回收()`（帧末 + 无引用才放）。
    @discardableResult
    func 删除(资产 id: UUID) -> 材质删除结果 {
        guard let 标 = 索引[id] else { return .未知材质 }
        let 计数 = 引用计数(资产: id)
        if 计数 > 0 {
            拒绝删除记录.append((材质: id, 引用者: 计数))
            return .拒绝仍有引用(引用者: Array(反向索引[标] ?? []).sorted { $0.uuidString < $1.uuidString })
        }
        guard 层.材质.请求延迟删除(标, 令牌: .材质) else {
            架构记录(.非所有者写入, "材质 \(id) 请求延迟删除被域拒绝")
            return .未知材质
        }
        索引[id] = nil
        反向索引[标] = nil
        for (对象, 表) in 正向索引 where 表.contains(标) {
            正向索引[对象] = 表.map { $0 == 标 ? nil : $0 }
        }
        // 这里**不**释放槽：受理删除只负责摘索引 + 排进待回收队列，
        // 槽的唯一释放时机是 `帧完成()` → `尝试回收()`（GPU 上可能还有帧在采样它）。
        return .已受理
    }

    /// 整体换库（载入存档 / 新建项目）：先把所有绑定解掉、旧材质全部删掉，再登记新的。
    /// 旧槽走请求延迟删除 → 待回收，GPU 还在用的帧不释放。
    func 换库(_ 列表: [MaterialAsset]) {
        for 对象 in Array(正向索引.keys) { _ = 解绑(对象: 对象) }
        for 资产 in 在册().map(\.记录.资产) { _ = 删除(资产: 资产.id) }
        for 资产 in 列表 { 登记(资产) }
    }

    // MARK: - 帧末回收（规矩 5 的唯一落地点）

    /// 消费端每提交一帧 GPU 命令缓冲调一次（渲染线程）。
    func 提交帧() {
        帧锁.lock()
        _在飞帧数 += 1
        帧锁.unlock()
        // 派生缓存回收也要看「有没有在飞帧」：帧里刚被读过的那几张此刻不能动
        视口纹理库.帧开始()
    }

    /// GPU 完成回调里切回主线程调一次：帧数归零后立刻尝试回收，返回本次真正释放的槽数。
    @discardableResult
    func 帧完成() -> Int {
        帧锁.lock()
        if _在飞帧数 > 0 { _在飞帧数 -= 1 }
        let 已清零 = _在飞帧数 == 0
        帧锁.unlock()
        guard 已清零 else { return 0 }
        // 先放掉「这一帧还读过」的标记，再让两边各按各的规矩回收：
        // 材质槽走域延迟删除，派生图看引用计数 + 字节上限，源图看引用 + 持有者。
        视口纹理库.帧结束()
        _ = 尝试释放源图()
        return 尝试回收()
    }

    /// 帧末回收（全工程唯一调用者 = `帧完成()`）：
    /// **材质已受理删除 + 无引用 + 没有任何一帧还在 GPU 上**，三者同时满足才释放槽。
    ///
    /// "GPU 还在用"的判据用 `在飞帧数 > 0` 而不是逐个材质猜：只要还有任何一条命令缓冲没完成，
    /// 就认为 GPU 可能仍持有这一批次的数据，一律不动；等帧完成回调落到 0 再来。
    /// 这样判据是保守的（宁可晚一帧），不会出现"槽被回收 + 立即复用，在飞帧读到新材质"的事故。
    @discardableResult
    func 尝试回收() -> Int {
        guard 在飞帧数 == 0 else { return 0 }
        let 数 = 层.回收材质(GPU仍在使用: { _ in false })
        if 数 > 0 {
            // 槽已释放：把索引里指向失效槽的键清掉（不清就会把悬空标识当有效材质用）
            let 失效 = 索引.filter { 层.材质.取($0.value) == nil }
            for (资产, 标) in 失效 {
                索引[资产] = nil
                反向索引[标] = nil
            }
        }
        return 数
    }
}

// MARK: - 源图受控接口（导入位图归材质域记账）

/// 【为什么要有这一层】
/// 早先 MTLX 接入、项目容器、网格材质都直接往 `视口纹理库` 这个全局单例里塞位图：
/// 登记完没谁负责回收，切项目只能靠 `只保留()` 一刀切，导入一次贴图就等于永久驻留；
/// 更麻烦的是「谁在用这张图」只在节点图里隐含表达，两处状态一旦不同步，
/// 就会出现「图还在库里、材质早就删了」这种越攒越大的死像素。
///
/// 现在源图的生杀大权全收在这一侧：
///  · 像素仍存在 `视口纹理库`（视口与路径追踪共用一份解码结果，不重复解码）；
///  · 但「谁在用」由材质域记账 —— 节点图的 image 引用 + 显式持有者（导入方 / 工程）；
///  · 释放只发生在 `帧完成()`（在飞帧清零）之后，且只释放「零引用」的图。
extension 材质接线 {
    /// 登记一张源图，返回可直接写进 imageTexture 节点的 UUID。
    /// - 参数 持有者：替这张图担保的对象（一般是导入它的材质 id）。拿不准就不传，
    ///   只要它还被节点图引用着就不会被回收。
    @discardableResult
    func 源图登记(_ 位图: CGImage, 字节 data: Data? = nil, id: UUID = UUID(), 持有者: UUID? = nil) -> UUID {
        视口纹理库.登记(位图, id: id, 字节: data)
        源图锁.lock()
        var 账 = 源图账本[id] ?? 源图账()
        if let data { 账.字节 = data }
        if let 持有者 { 账.持有者.insert(持有者) }
        源图账本[id] = 账
        源图锁.unlock()
        return id
    }

    /// 从文件字节登记（项目载入 / 存档解码用）：解码成图 + 保留原字节。
    /// UUID 必须沿用存档里那个 —— 节点图存的就是它，跨重启必须对得上。
    @discardableResult
    func 源图载入(_ data: Data, id: UUID, 持有者: UUID? = nil) -> Bool {
        guard 视口纹理库.登记字节(data, id: id) else { return false }
        源图锁.lock()
        var 账 = 源图账本[id] ?? 源图账()
        账.字节 = data
        if let 持有者 { 账.持有者.insert(持有者) }
        源图账本[id] = 账
        源图锁.unlock()
        return true
    }

    /// 当前库里的全部源图字节（存档写盘用）。只给「库还在的」，死引用不会混进新档。
    func 全部源图字节() -> [UUID: Data] {
        视口纹理库.全部字节()
    }

    /// 把库裁成给定的这一批（切工程时调用）：
    /// 「本工程的贴图 = 库里的贴图」，别的工程留下的图不会跟着下一次保存被写进来。
    func 源图只保留(_ ids: Set<UUID>) {
        视口纹理库.只保留(ids)
        源图锁.lock()
        源图账本 = 源图账本.filter { ids.contains($0.key) }
        源图锁.unlock()
    }

    /// 加一个持有者（例如材质刚建好，认领了导入期登记的那张图）
    func 源图加持有者(_ id: UUID, _ 持有者: UUID) {
        源图锁.lock()
        var 账 = 源图账本[id] ?? 源图账()
        账.持有者.insert(持有者)
        源图账本[id] = 账
        源图锁.unlock()
    }

    func 源图去持有者(_ id: UUID, _ 持有者: UUID) {
        源图锁.lock()
        if var 账 = 源图账本[id] {
            账.持有者.remove(持有者)
            源图账本[id] = 账
        }
        源图锁.unlock()
    }

    /// 当前材质库里被节点图引用的源图计数。
    /// 数的是**全部 image 节点**，包括没连到输出口的游离节点 —— 那是用户手上的资产，
    /// 不能因为「暂时没连线」就被当成垃圾回收掉。
    func 源图引用快照() -> [UUID: Int] {
        var 计: [UUID: Int] = [:]
        // 只认在册材质：已删待回收的那条不该继续为它的贴图担保，否则源图会白等到下一轮
        for 项 in 在册() {
            for 节点 in 项.记录.资产.graph.nodes {
                guard let 图 = 节点.image else { continue }
                计[图, default: 0] += 1
            }
        }
        return 计
    }

    /// 一张源图现在有几个引用（节点引用 + 显式持有者）
    func 源图引用计数(_ id: UUID) -> Int {
        源图锁.lock()
        let 持有 = 源图账本[id]?.持有者.count ?? 0
        源图锁.unlock()
        return 持有 + (源图引用快照()[id] ?? 0)
    }

    /// 释放零引用的源图，返回真正被释放的张数。
    /// 只在 `帧完成()`（在飞帧清零）里调：正在渲染的那一帧可能刚拿过这张图。
    @discardableResult
    func 尝试释放源图() -> Int {
        guard 在飞帧数 == 0 else { return 0 }
        源图锁.lock()
        let 全部账 = Array(源图账本.keys)
        源图锁.unlock()
        guard !全部账.isEmpty else { return 0 }
        let 引用 = 源图引用快照()
        var 释放: Set<UUID> = []
        for id in 全部账 {
            源图锁.lock()
            let 持有 = 源图账本[id]?.持有者.count ?? 0
            源图锁.unlock()
            if 持有 == 0 && (引用[id] ?? 0) == 0 { 释放.insert(id) }
        }
        guard !释放.isEmpty else { return 0 }
        视口纹理库.移除(释放)
        源图锁.lock()
        for id in 释放 { 源图账本[id] = nil }
        源图锁.unlock()
        return 释放.count
    }

    /// 源图账目快照（诊断 / 设置页显示）
    var 源图占用: (张数: Int, 字节: Int, 代际: UInt64) {
        源图锁.lock()
        let 账 = 源图账本
        源图锁.unlock()
        let 字节数 = 账.values.reduce(0) { $0 + ($1.字节?.count ?? 0) }
        return (视口纹理库.全部字节().count, 字节数, 视口纹理库.源图代际)
    }
}

