import Foundation

// MARK: - 版本号

/// 四个域 + 关节各自的单调版本号。消费者按版本号自行判断要不要更新，别去猜。
struct 场景版本: Equatable {
    var 几何: UInt64
    var 材质: UInt64
    var 灯光: UInt64
    /// 注意口径：这是**整域**写入次数版本（灯和物体混在一起），只用于"抓快照期间有没有人动数据层"的告警。
    /// 判定"物体变换变没变"必须用 变换接线.取非灯变换版本()；判定"灯变没变"用 灯光记账.变换。
    /// 拿它当渲染判据会让拖灯被误判成拖物体（整棵加速结构白 refit）。
    var 变换: UInt64
    var 对象: UInt64

    static let 初始 = 场景版本(几何: 0, 材质: 0, 灯光: 0, 变换: 0, 对象: 0)
}

// MARK: - 场景数据层

/// 场景数据层：只是四个域 + 关节表的**聚合入口**，自身不存任何数据，
/// 因此不存在"第二份所有者"。写操作一律走各域，且必须带对应域的所有者令牌。
///
/// 依赖方向：数据层不知道渲染器的存在，不 import 任何渲染模式、不引用 PT*；
/// 渲染模式只能从 场景快照 读；域与域之间互不调用，只通过稳定 id 互相引用
/// （唯一例外是 对象关节表 的只读校验，它是设计上的 M:N 连接者）。
final class 场景数据层 {

    /// 全进程唯一一份数据层。灯、物体、渲染器读到的必须是同一棵树 ——
    /// 以前灯光接线自己 new 一个 场景数据层，等于开了第二份所有者，跟"唯一所有者"直接冲突。
    static let 共享 = 场景数据层()

    let 几何: 几何域
    let 材质: 材质域
    let 灯光: 灯光域
    let 变换: 变换域
    let 对象: 对象关节表

    init() {
        几何 = 几何域(所有者: .几何)
        材质 = 材质域(所有者: .材质)
        灯光 = 灯光域(所有者: .灯光)
        变换 = 变换域()
        对象 = 对象关节表()

        // 规矩 1 的运行期形态：同一概念只许登记一个所有者，重复登记会当场断言。
        所有权登记表.共享.登记(概念: ["几何", "网格形状", "网格包围盒"], 令牌: .几何)
        所有权登记表.共享.登记(概念: ["材质", "材质槽映射"], 令牌: .材质)
        所有权登记表.共享.登记(概念: ["灯光", "灯参数"], 令牌: .灯光)
        所有权登记表.共享.登记(概念: ["变换", "父子层级", "世界矩阵"], 令牌: .变换)
        所有权登记表.共享.登记(概念: ["对象", "实例", "材质分配", "几何↔对象关系"], 令牌: .对象)
    }

    var 版本: 场景版本 {
        场景版本(
            几何: 几何.版本号,
            材质: 材质.版本号,
            灯光: 灯光.版本号,
            变换: 变换.版本号,
            对象: 对象.版本号
        )
    }

    /// 生成不可变快照（零拷贝：只拿只读视图）。
    func 生成快照() -> 场景快照 { 场景快照(层: self) }

    /// 引用回收轮询：逐域进行，GPU 说还在用就留着，确认没人引用且 GPU 用完才真删（规矩 5）。
    /// 消费端（阶段 2 后续）在每帧提交后调用；本轮空转，没有任何调用点。
    @discardableResult
    func 回收几何(GPU仍在使用: (稳定标识<几何域标签>) -> Bool) -> Int {
        几何.轮询回收(令牌: .几何, GPU仍在使用: GPU仍在使用)
    }

    @discardableResult
    func 回收材质(GPU仍在使用: (稳定标识<材质域标签>) -> Bool) -> Int {
        材质.轮询回收(令牌: .材质, GPU仍在使用: GPU仍在使用)
    }

    @discardableResult
    func 回收灯光(GPU仍在使用: (稳定标识<灯光域标签>) -> Bool) -> Int {
        灯光.轮询回收(令牌: .灯光, GPU仍在使用: GPU仍在使用)
    }

    @discardableResult
    func 回收变换(GPU仍在使用: (稳定标识<变换域标签>) -> Bool) -> Int {
        变换.存储.轮询回收(令牌: .变换, GPU仍在使用: GPU仍在使用)
    }
}

// MARK: - 场景快照

/// 灯光段的两个记账版本号。
///
/// 为什么不用 `版本.灯光` / `版本.变换` 直接当灯版本：
/// - 灯光域里只有灯，参数版本可以用域版本号；但"朝向"也在灯光域里，语义同属灯光段，故合并。
/// - 变换域是所有对象共用的：拖一个箱子也会让 `版本.变换` 自增。用它当"灯变换版本"会把
///   "物体动了"误判成"灯动了"，正是本轮要消灭的误判。灯矩阵版本因此由灯光接线（灯矩阵的
///   唯一写入方）在写入时按等价性单独记账 —— 仍然是版本号，不是哈希签名。
struct 灯光版本记账: Equatable {
    var 参数: UInt64
    var 变换: UInt64

    static let 零 = 灯光版本记账(参数: 0, 变换: 0)
}

/// 几何段的记账版本号。
///
/// 为什么不用 `版本.几何` 直接当几何段版本：那是**整域写入次数**（改名、引用计数都会推），
/// 而几何段要的是"这份几何的内容变没变"。内容版本由几何接线（几何的唯一写入方）在写入时
/// 按等价性单独记账 —— 与灯光记账同构，仍然是单调版本号，不是哈希签名。
struct 几何版本记账: Equatable {
    var 内容: UInt64

    static let 零 = 几何版本记账(内容: 0)
}

/// 场景快照：不可变，四个域各带一个独立版本号，消费者按版本号自行决定更新范围。
/// 只持有各域的只读视图（引用），**不复制记录**（规矩 7）。
struct 场景快照 {

    let 版本: 场景版本

    /// 灯光段版本号：由灯光接线在生成快照后回填（默认零，表示"未接灯"）。
    var 灯光记账: 灯光版本记账 = .零

    /// 几何段版本号：由几何接线在生成快照后回填（默认零，表示"未接几何"）。
    var 几何记账: 几何版本记账 = .零

    let 几何: 几何视图
    let 材质: 材质视图
    let 灯光: 灯光视图
    let 变换: 变换视图
    let 对象: 对象视图

    init(层: 场景数据层) {
        let 取版本前 = 层.版本

        几何 = 域只读视图(层.几何)
        材质 = 域只读视图(层.材质)
        灯光 = 域只读视图(层.灯光)
        变换 = 层.变换.只读视图()
        对象 = 层.对象.只读视图()

        版本 = 场景版本(
            几何: 几何.版本号,
            材质: 材质.版本号,
            灯光: 灯光.版本号,
            变换: 变换.版本号,
            对象: 对象.版本号
        )

        // 抓快照期间不许有人改数据层：五个版本号必须原封不动。
        if 版本 != 取版本前 {
            架构记录(.快照版本不一致, "生成快照期间版本号发生变化：取前 \(取版本前)，取后 \(版本)")
        }
    }

    /// 快照是否相对数据层已过期。消费者用它判断"要不要重读"，而不是自己猜。
    func 是否过期(相对 层: 场景数据层) -> Bool {
        版本 != 层.版本
    }

    func 是否过期(相对 其它: 场景快照) -> Bool {
        版本 != 其它.版本
    }

    /// 空场景判定：供后续消费者使用（本轮无人调用，避免影响现有空屏逻辑）。
    var 是空场景: Bool { 对象.数量 == 0 }
}
