import Foundation

// MARK: - 域标记
//
// 每个域一个空枚举当"域标签"，只用于把稳定标识在类型层面绑到某个域上。
// 空枚举无法实例化，也不会带来任何运行时开销。
// 好处：几何 id 传进材质域会编译不过，跨域混用在这里就被拦下来了。

enum 几何域标签 {}
enum 材质域标签 {}
enum 灯光域标签 {}
enum 变换域标签 {}
enum 对象域标签 {}

// MARK: - 稳定标识

/// 域内记录的稳定标识。
///
/// 由 (槽位, 代际) 组成：槽位会被复用，但每次复用代际 +1，
/// 所以「旧 id ≠ 复用后的新记录」——旧 id 永远查不到东西，不会指向别人的数据。
/// 下标只在域内部临时使用，出了域一律包成这个类型，满足「禁止以下标作为长期引用」。
struct 稳定标识<域>: Hashable, Codable, CustomStringConvertible {

    let 槽位: Int
    let 代际: UInt32

    init(槽位: Int, 代际: UInt32) {
        self.槽位 = 槽位
        self.代际 = 代际
    }

    var description: String {
        "\(String(describing: 域.self))#\(槽位)@v\(代际)"
    }

    /// 压成 64 位整数，只给日志与统计用，不参与语义判断。
    var 压缩值: UInt64 {
        (UInt64(代际) << 32) | UInt64(UInt32(truncatingIfNeeded: 槽位))
    }
}

// MARK: - 域违规

/// 数据层内部所有可检测违规的统一出口。
/// 规矩要求「异常一律断言 + 日志，不重建不重试」，所以这里只描述问题，不提供任何修复动作。
enum 域违规: Error, Equatable {

    /// 非所有者想写这个域（规矩 1 / 规矩 2）
    case 非所有者写入(要求: String, 实际: String)
    /// 标识失效：槽位越界、代际不符、槽已空 —— 等价于「把下标当引用」（规矩 4）
    case 下标作引用(细节: String)
    /// 标识从来没存在过
    case 未知标识(细节: String)
    /// 引用计数与占用不符（规矩 5）
    case 引用计数污染(细节: String)
    /// 变换链成环（规矩 6）
    case 成环(细节: String)
    /// 关节点指向了不存在的记录，或同一对象既是几何又是灯
    case 悬空引用(细节: String)
    /// 1:1 关系被写成 1:N
    case 一对多(细节: String)
    /// 同一概念出现第二个所有者（规矩 1：唯一所有者）
    case 重复所有者(细节: String)

    var 描述: String {
        switch self {
        case let .非所有者写入(要求, 实际):
            return "非所有者写入：本域所有者是 \(要求)，写入方自称 \(实际)"
        case let .下标作引用(细节):
            return "标识失效（疑似拿下标当引用）：\(细节)"
        case let .未知标识(细节):
            return "未知标识：\(细节)"
        case let .引用计数污染(细节):
            return "引用计数异常：\(细节)"
        case let .成环(细节):
            return "变换链成环：\(细节)"
        case let .悬空引用(细节):
            return "引用悬空：\(细节)"
        case let .一对多(细节):
            return "1:1 关系被写成 1:N：\(细节)"
        case let .重复所有者(细节):
            return "重复所有者：\(细节)"
        }
    }
}

// MARK: - 记录域

/// 通用记录域：稳定 id → 记录，带脏标记、单调版本号、引用计数与延迟回收。
///
/// **粒度选择：数组存槽 + 空闲槽栈（不紧凑化），而不是字典。**
/// 理由：
/// 1. 遍历是热路径（每帧要刷几何/灯光的 GPU 缓冲），数组内存连续，遍历无哈希开销；
///    字典每帧遍历会带来不可避免的哈希桶跳转与额外内存间接。
/// 2. 不紧凑化是为了让稳定 id 里的槽位永远有效：一旦紧凑化，已有 id 的槽位会漂移，
///    等于把"下标当引用"。空槽靠代际挡住悬空访问，空间浪费可接受（槽本身很小）。
/// 3. 单条取用是 O(1)：槽位直接当数组下标，再用代际校验一次，不需要 id→index 的字典。
/// 4. 删除密集的场景由空闲槽栈复用，不会让槽表无限膨胀。
///
/// 写入口一律要求传"所有者令牌"，令牌不符直接拒绝并断言 —— 这就是规矩 1、2 的代码形态。
final class 记录域<域, 元素> {

    struct 槽 {
        var 代际: UInt32
        var 元素: 元素?
        var 脏: Bool
        var 引用计数: Int
        var 待删除: Bool

        init(代际: UInt32, 元素: 元素?) {
            self.代际 = 代际
            self.元素 = 元素
            self.脏 = 元素 != nil
            self.引用计数 = 0
            self.待删除 = false
        }
    }

    let 所有者: 所有者令牌

    private(set) var 槽表: [槽] = []
    private(set) var 版本号: UInt64 = 0

    private var 空闲槽: [Int] = []
    private var 待回收: [稳定标识<域>] = []

    init(所有者: 所有者令牌) {
        self.所有者 = 所有者
    }

    // MARK: 只读

    var 有效数量: Int {
        槽表.reduce(0) { $0 + ($1.元素 == nil ? 0 : 1) }
    }

    var 待回收数量: Int { 待回收.count }

    /// 检测标识是否仍然有效（只判断，不写日志、不修复）—— 自检与断言都走这里。
    func 检测标识(_ id: 稳定标识<域>) -> 域违规? {
        guard id.槽位 >= 0 else {
            return .下标作引用(细节: "槽位为负 \(id.槽位)")
        }
        guard id.槽位 < 槽表.count else {
            return .下标作引用(细节: "槽位越界 \(id.槽位) ≥ 槽表长度 \(槽表.count)")
        }
        let 槽 = 槽表[id.槽位]
        if 槽.元素 == nil {
            return .下标作引用(细节: "\(id.槽位) 号槽已释放，旧标识不可再用")
        }
        if 槽.代际 != id.代际 {
            return .下标作引用(细节: "代际不符：标识 v\(id.代际)，槽内 v\(槽.代际)")
        }
        return nil
    }

    /// 预检写入权限（规矩 1、2 的唯一判定点）。
    func 预检写入(_ 写令牌: 所有者令牌) -> 域违规? {
        写令牌 == 所有者 ? nil : .非所有者写入(要求: 所有者.名称, 实际: 写令牌.名称)
    }

    func 取(_ id: 稳定标识<域>) -> 元素? {
        if let 违规 = 检测标识(id) {
            架构记录(.下标作引用, "\(所有者.名称) 读取 \(id) 失败：\(违规.描述)")
            return nil
        }
        return 槽表[id.槽位].元素
    }

    func 遍历(_ 体: (稳定标识<域>, 元素) -> Void) {
        for 索引 in 槽表.indices {
            guard let 值 = 槽表[索引].元素 else { continue }
            体(稳定标识(槽位: 索引, 代际: 槽表[索引].代际), 值)
        }
    }

    func 全部标识() -> [稳定标识<域>] {
        var 结果: [稳定标识<域>] = []
        结果.reserveCapacity(有效数量)
        for 索引 in 槽表.indices where 槽表[索引].元素 != nil {
            结果.append(稳定标识(槽位: 索引, 代际: 槽表[索引].代际))
        }
        return 结果
    }

    func 脏标识() -> [稳定标识<域>] {
        var 结果: [稳定标识<域>] = []
        for 索引 in 槽表.indices where 槽表[索引].元素 != nil && 槽表[索引].脏 {
            结果.append(稳定标识(槽位: 索引, 代际: 槽表[索引].代际))
        }
        return 结果
    }

    func 引用计数(_ id: 稳定标识<域>) -> Int? {
        guard 检测标识(id) == nil else { return nil }
        return 槽表[id.槽位].引用计数
    }

    // MARK: 写（仅所有者）

    @discardableResult
    func 新增(_ 元素: 元素, 令牌 写令牌: 所有者令牌) -> 稳定标识<域>? {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的新增：\(违规.描述)")
            return nil
        }

        let 槽位索引: Int
        if let 复用 = 空闲槽.popLast() {
            槽表[复用].元素 = 元素
            槽表[复用].脏 = true
            槽表[复用].引用计数 = 0
            槽表[复用].待删除 = false
            槽位索引 = 复用
        } else {
            槽表.append(槽(代际: 1, 元素: 元素))
            槽位索引 = 槽表.count - 1
        }
        版本号 &+= 1
        return 稳定标识(槽位: 槽位索引, 代际: 槽表[槽位索引].代际)
    }

    @discardableResult
    func 改(
        _ id: 稳定标识<域>,
        令牌 写令牌: 所有者令牌,
        _ 体: (inout 元素) -> Void
    ) -> Bool {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的改写：\(违规.描述)")
            return false
        }
        if let 违规 = 检测标识(id) {
            架构记录(.下标作引用, "\(所有者.名称) 改写 \(id) 失败：\(违规.描述)")
            return false
        }
        guard var 值 = 槽表[id.槽位].元素 else { return false }
        体(&值)
        槽表[id.槽位].元素 = 值
        槽表[id.槽位].脏 = true
        版本号 &+= 1
        return true
    }

    @discardableResult
    func 批量标脏<S: Sequence>(_ 标识集: S, 令牌 写令牌: 所有者令牌) -> Int
    where S.Element == 稳定标识<域> {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的批量标脏：\(违规.描述)")
            return 0
        }
        var 计数 = 0
        for id in 标识集 where 检测标识(id) == nil {
            槽表[id.槽位].脏 = true
            计数 += 1
        }
        if 计数 > 0 { 版本号 &+= UInt64(计数) }
        return 计数
    }

    /// 清除脏标记。版本号不回落：版本号是单调语义，只增不减。
    func 清脏(_ id: 稳定标识<域>) {
        guard 检测标识(id) == nil else { return }
        槽表[id.槽位].脏 = false
    }

    // MARK: 引用计数 + 延迟回收（规矩 5）

    @discardableResult
    func 增引用(_ id: 稳定标识<域>, 令牌 写令牌: 所有者令牌) -> Bool {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的增引用：\(违规.描述)")
            return false
        }
        guard 检测标识(id) == nil else {
            架构记录(.下标作引用, "\(所有者.名称) 增引用失败：\(id) 无效")
            return false
        }
        if 槽表[id.槽位].待删除 {
            架构记录(.引用计数, "\(id) 已进入待回收队列，不允许再被引用")
            return false
        }
        槽表[id.槽位].引用计数 += 1
        return true
    }

    @discardableResult
    func 减引用(_ id: 稳定标识<域>, 令牌 写令牌: 所有者令牌) -> Bool {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的减引用：\(违规.描述)")
            return false
        }
        guard 检测标识(id) == nil else {
            架构记录(.下标作引用, "\(所有者.名称) 减引用失败：\(id) 无效")
            return false
        }
        guard 槽表[id.槽位].引用计数 > 0 else {
            架构记录(.引用计数, "\(id) 引用计数已是 0，不能再减")
            return false
        }
        槽表[id.槽位].引用计数 -= 1
        if 槽表[id.槽位].引用计数 == 0 && 槽表[id.槽位].待删除 {
            return true
        }
        return true
    }

    /// 请求删除：仍有引用就挂进待回收队列，不立刻释放（规矩 5）。
    @discardableResult
    func 请求删除(_ id: 稳定标识<域>, 令牌 写令牌: 所有者令牌) -> Bool {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的删除：\(违规.描述)")
            return false
        }
        guard 检测标识(id) == nil else {
            架构记录(.下标作引用, "\(所有者.名称) 删除失败：\(id) 无效")
            return false
        }
        if 槽表[id.槽位].引用计数 > 0 {
            槽表[id.槽位].待删除 = true
            if !待回收.contains(id) { 待回收.append(id) }
            return true
        }
        释放槽(id.槽位)
        版本号 &+= 1
        return true
    }

    /// 请求延迟删除：**无引用也不立刻释放**，直接挂进待回收队列，等帧末轮询回收。
    ///
    /// 材质域专用口径：材质的"还有没有人用"由材质接线从对象槽位表派生，域槽上的 `引用计数`
    /// 不再参与材质判定；而 GPU 那一侧必须等命令缓冲落定才能释放槽，所以材质删除一律走这里，
    /// 不走「计数为 0 就当场释放」的快路径。其它域继续用 `请求删除`，行为不变。
    @discardableResult
    func 请求延迟删除(_ id: 稳定标识<域>, 令牌 写令牌: 所有者令牌) -> Bool {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的延迟删除：\(违规.描述)")
            return false
        }
        guard 检测标识(id) == nil else {
            架构记录(.下标作引用, "\(所有者.名称) 延迟删除失败：\(id) 无效")
            return false
        }
        if 槽表[id.槽位].待删除 { return true }
        槽表[id.槽位].待删除 = true
        待回收.append(id)
        return true
    }

    /// 回收轮询：只有「引用计数归零」且「GPU 确认不再使用」才真删。
    @discardableResult
    func 轮询回收(令牌 写令牌: 所有者令牌, GPU仍在使用: (稳定标识<域>) -> Bool) -> Int {
        if let 违规 = 预检写入(写令牌) {
            架构记录(.非所有者写入, "\(所有者.名称) 拒绝 \(写令牌.名称) 的回收：\(违规.描述)")
            return 0
        }
        var 回收数 = 0
        var 保留: [稳定标识<域>] = []
        for id in 待回收 {
            guard 检测标识(id) == nil else { continue }
            if 槽表[id.槽位].引用计数 > 0 {
                保留.append(id)
                continue
            }
            if GPU仍在使用(id) {
                保留.append(id)
                continue
            }
            释放槽(id.槽位)
            回收数 += 1
        }
        待回收 = 保留
        if 回收数 > 0 { 版本号 &+= UInt64(回收数) }
        return 回收数
    }

    func 待回收清单() -> [稳定标识<域>] { 待回收 }

    private func 释放槽(_ 槽位: Int) {
        槽表[槽位].元素 = nil
        槽表[槽位].脏 = false
        槽表[槽位].引用计数 = 0
        槽表[槽位].待删除 = false
        槽表[槽位].代际 = 槽表[槽位].代际 &+ 1
        空闲槽.append(槽位)
        待回收.removeAll { $0.槽位 == 槽位 }
    }
}

// MARK: - 域只读视图

/// 快照用的只读视图：**只持有源域的引用，不复制任何记录**（规矩 7：派生零拷贝）。
/// 类型上根本没有写入口，所以消费者拿不到"顺手改一下"的可能。
struct 域只读视图<域, 元素> {

    private let 源: 记录域<域, 元素>

    /// 建视图那一刻的域版本号，用于判断快照是否过期。
    let 版本号: UInt64
    let 所有者名称: String

    init(_ 源: 记录域<域, 元素>) {
        self.源 = 源
        self.版本号 = 源.版本号
        self.所有者名称 = 源.所有者.名称
    }

    var 数量: Int { 源.有效数量 }

    func 取(_ id: 稳定标识<域>) -> 元素? { 源.取(id) }

    func 遍历(_ 体: (稳定标识<域>, 元素) -> Void) { 源.遍历(体) }

    func 全部标识() -> [稳定标识<域>] { 源.全部标识() }

    func 是否仍是最新(_ 层: 记录域<域, 元素>) -> Bool { 层.版本号 == 版本号 }
}

// MARK: - 架构约束（所有权令牌 / 违规记录 / 所有权登记，原「架构 约束.swift」）

// MARK: - 所有者令牌

/// 每个域的唯一身份证。写操作必须带上对应的令牌，否则拒绝并断言。
/// 这是规矩 1（唯一所有者）与规矩 2（单向依赖）的代码形态：
/// 拿不到令牌就写不进去，跨域直写在这里就编译期/运行期双双走不通。
struct 所有者令牌: Equatable, Sendable {

    let 名称: String

    init(名称: String) {
        self.名称 = 名称
    }

    static let 几何 = 所有者令牌(名称: "几何域")
    static let 材质 = 所有者令牌(名称: "材质域")
    static let 灯光 = 所有者令牌(名称: "灯光域")
    static let 变换 = 所有者令牌(名称: "变换域")
    static let 对象 = 所有者令牌(名称: "对象关节表")
}

// MARK: - 架构违规

/// 数据层能自动判定的违规类型。规矩 3：异常只做「断言 + 日志」，绝不重建/重试/自动恢复。
enum 架构违规: String {
    case 重复所有者 = "同一概念出现第二个所有者"
    case 非所有者写入 = "非所有者写入"
    case 跨域直调 = "跨域直接调用"
    case 下标作引用 = "把槽位下标当长期引用"
    case 未知标识 = "未知标识"
    case 引用计数 = "引用计数与占用不符"
    case 成环 = "变换链成环"
    case 关节点悬空 = "关节点引用悬空"
    case 关节一对多 = "1:1 关系被写成 1:N"
    case 快照版本不一致 = "快照版本号与域不一致"
}

/// 违规统一出口：Debug 当场炸（assertionFailure），Release 打到 stderr，绝不静默吞掉。
func 架构记录(
    _ 违规: 架构违规,
    _ 细节: String = "",
    file: StaticString = #fileID,
    line: UInt = #line
) {
    let 行 = "【数据层·架构违规】[\(违规.rawValue)] \(细节) @\(file):\(line)"
    #if DEBUG
    assertionFailure(行)
    #else
    FileHandle.standardError.write(Data((行 + "\n").utf8))
    #endif
}

/// 条件断言：不成立即按违规处理。返回值只是给 Release 分支留一个可判断的出口。
@discardableResult
func 架构断言(
    _ 条件: @autoclosure () -> Bool,
    _ 违规: 架构违规,
    _ 细节: @autoclosure () -> String = "",
    file: StaticString = #fileID,
    line: UInt = #line
) -> Bool {
    if 条件() { return true }
    架构记录(违规, 细节(), file: file, line: line)
    return false
}

/// 关节层的关系违规映射到架构违规，便于日志一眼看懂是哪条规矩破了。
func 关系违规转架构(_ 违规: 域违规) -> 架构违规 {
    if case .一对多 = 违规 { return .关节一对多 }
    return .关节点悬空
}

// MARK: - 所有权登记表（规矩 1）

/// 概念 → 唯一所有者。任何新概念要先在这里登记，重复登记会被当成"第二份实现"当场断言。
final class 所有权登记表 {

    static let 共享 = 所有权登记表()

    private(set) var 概念归属: [String: 所有者令牌] = [:]

    /// 业务代码一律用 .共享；自检为了不污染全局归属表才需要独立实例。
    init() {}

    func 检测登记冲突(_ 概念: String, 令牌: 所有者令牌) -> 域违规? {
        if let 已有 = 概念归属[概念], 已有 != 令牌 {
            return .重复所有者(细节: "概念「\(概念)」已由 \(已有.名称) 拥有，\(令牌.名称) 不许再定义第二份")
        }
        return nil
    }

    @discardableResult
    func 登记(概念: String, 令牌: 所有者令牌) -> 域违规? {
        if let 违规 = 检测登记冲突(概念, 令牌: 令牌) {
            架构记录(.重复所有者, 违规.描述)
            return 违规
        }
        概念归属[概念] = 令牌
        return nil
    }

    @discardableResult
    func 登记(概念 列表: [String], 令牌: 所有者令牌) -> [域违规] {
        var 结果: [域违规] = []
        for 概念 in 列表 {
            if let 违规 = 登记(概念: 概念, 令牌: 令牌) { 结果.append(违规) }
        }
        return 结果
    }
}

// MARK: - 数据层自检
//
// 只调用各域的「检测」入口（不写日志、不触发断言），所以自检本身不会把 App 打断。
// 返回空数组 = 七条规矩里可自动校验的部分全部生效。

@discardableResult
func 数据层自检() -> [String] {

    var 问题: [String] = []

    // 规矩 1：唯一所有者 —— 同一概念第二个所有者必须被拒
    let 登记 = 所有权登记表()
    _ = 登记.登记(概念: "几何", 令牌: .几何)
    if 登记.检测登记冲突("几何", 令牌: .材质) == nil {
        问题.append("规矩1 未拦住：同一概念被第二个所有者登记成功")
    }

    // 规矩 2：单向依赖 —— 非所有者令牌写不进别人的域
    let 材质试写 = 材质域(所有者: .材质)
    if 材质试写.预检写入(.几何) == nil {
        问题.append("规矩2 未拦住：几何令牌可以写材质域")
    }
    // 新增/改写都走同一个判定点（预检写入），这里只验判定点本身，不再触发一次断言
    if 材质试写.预检写入(.材质) != nil {
        问题.append("规矩2 误报：所有者令牌被自己拒绝")
    }

    // 规矩 3：禁止容错重建 —— 非法访问只报错，不自动补建、不改版本号
    let 几何试 = 几何域(所有者: .几何)
    let 几何版本前 = 几何试.版本号
    if 几何试.检测标识(稳定标识<几何域标签>(槽位: 99, 代际: 1)) == nil {
        问题.append("规矩3 未判定：越界标识被当成有效")
    }
    if 几何试.版本号 != 几何版本前 || 几何试.有效数量 != 0 {
        问题.append("规矩3 未通过：非法访问后域被自动修补（容错重建）")
    }

    // 规矩 4：稳定 id —— 删除后旧标识彻底失效，复用槽位必须升代际
    let 材质试 = 材质域(所有者: .材质)
    guard let 材质甲 = 材质试.新增(材质记录(名称: "甲"), 令牌: .材质) else {
        问题.append("规矩4 前置失败：新增被拒")
        return 问题
    }
    _ = 材质试.请求删除(材质甲, 令牌: .材质)
    if 材质试.检测标识(材质甲) == nil {
        问题.append("规矩4 未通过：删除后旧标识仍然有效")
    }
    guard let 材质乙 = 材质试.新增(材质记录(名称: "乙"), 令牌: .材质) else {
        问题.append("规矩4 前置失败：槽位复用新增被拒")
        return 问题
    }
    if 材质甲.槽位 == 材质乙.槽位 && 材质甲.代际 == 材质乙.代际 {
        问题.append("规矩4 未通过：复用槽位没有升代际（旧 id 会指向新记录）")
    }
    if 材质甲 == 材质乙 {
        问题.append("规矩4 未通过：新旧记录撞号")
    }

    // 规矩 5：引用计数 + 延迟回收 —— 有引用不许释放，GPU 还在用不许释放
    let 灯光试 = 灯光域(所有者: .灯光)
    guard let 灯 = 灯光试.新增(灯光记录(名称: "试灯"), 令牌: .灯光) else {
        问题.append("规矩5 前置失败：灯光新增被拒")
        return 问题
    }
    _ = 灯光试.增引用(灯, 令牌: .灯光)
    _ = 灯光试.请求删除(灯, 令牌: .灯光)
    if 灯光试.取(灯) == nil {
        问题.append("规矩5 未通过：仍有引用就直接释放了")
    }
    if 灯光试.轮询回收(令牌: .灯光, GPU仍在使用: { _ in true }) != 0 || 灯光试.取(灯) == nil {
        问题.append("规矩5 未通过：GPU 仍在使用就回收了")
    }
    _ = 灯光试.减引用(灯, 令牌: .灯光)
    if 灯光试.轮询回收(令牌: .灯光, GPU仍在使用: { _ in false }) != 1 {
        问题.append("规矩5 未通过：无引用且 GPU 空闲仍未回收")
    }
    if 灯光试.取(灯) != nil {
        问题.append("规矩5 未通过：回收后仍能读到记录")
    }

    // 规矩 6：变换链拒绝成环
    let 变换试 = 变换域()
    guard let 变换甲 = 变换试.新增(变换记录(名称: "甲"), 令牌: .变换),
           let 变换乙 = 变换试.新增(变换记录(名称: "乙"), 令牌: .变换) else {
        问题.append("规矩6 前置失败：变换新增被拒")
        return 问题
    }
    if 变换试.设父(变换乙, 父: 变换甲, 令牌: .变换) != nil {
        问题.append("规矩6 前置失败：合法挂父被拒")
    }
    if 变换试.检测成环(变换甲, 新父: 变换乙) == nil {
        问题.append("规矩6 未拦住：甲→乙→甲 成环")
    }
    if 变换试.检测成环(变换甲, 新父: 变换甲) == nil {
        问题.append("规矩6 未拦住：自环")
    }

    // 规矩 7：派生零拷贝 + 快照版本独立
    let 层 = 场景数据层()
    guard let 几何id = 层.几何.新增(几何记录(名称: "球", 来源: .程序网格(.sphere)), 令牌: .几何),
           let 变换id = 层.变换.新增(变换记录(名称: "球变换"), 令牌: .变换),
           let 对象id = 层.对象.新增(对象关节记录(名称: "球", 几何: 几何id, 变换: 变换id), 令牌: .对象) else {
        问题.append("规矩7 前置失败：数据层建对象被拒")
        return 问题
    }
    let 快照1 = 层.生成快照()
    if 快照1.几何.取(几何id) == nil || 快照1.对象.取(对象id) == nil {
        问题.append("规矩7 未通过：快照读不到域内记录")
    }
    _ = 层.材质.新增(材质记录(名称: "新材质"), 令牌: .材质)
    let 快照2 = 层.生成快照()
    if !快照1.是否过期(相对: 层) {
        问题.append("规矩7 未通过：域变了旧快照没被标记过期")
    }
    if 快照1.版本.材质 == 快照2.版本.材质 {
        问题.append("规矩7 未通过：材质版本号没有前进")
    }
    if 快照1.版本.几何 != 快照2.版本.几何 {
        问题.append("规矩7 未通过：没动几何，几何版本却变了（版本粒度错了）")
    }
    let 悬空 = 层.对象.校验引用(几何域: 层.几何, 材质域: 层.材质, 灯光域: 层.灯光, 变换域: 层.变换)
    if !悬空.isEmpty {
        问题.append("关节校验误报：\(悬空.map(\.描述))")
    }
    if 层.对象.检测关系(对象关节记录(名称: "球2", 几何: 几何id, 变换: 变换id), 排除: nil) == nil {
        问题.append("1:1 未拦住：同一个变换被第二个对象占用")
    }

    return 问题
}
