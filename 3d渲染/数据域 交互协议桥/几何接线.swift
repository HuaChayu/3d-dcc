import RealityKit
import Foundation

// MARK: - 几何源取值（消费端唯一可见的几何形态）

/// 一个物体在消费端的样子：几何来源只从几何域取，消费端不再回头读
/// `SceneObject.mesh` / `SceneObject.导入网格ID`（规矩 1：几何的唯一所有者是几何域）。
struct 几何源取值: Equatable {
    var 外部键: String
    var 名称: String
    /// 几何域记录的来源：程序网格形状 or 导入网格 UUID。
    /// 形状枚举只有 `MeshKind` 一份（规矩 7 第 5 条：不许定义第二份形状枚举）。
    var 来源: 几何来源
    /// 导入网格库的内容版本（程序网格恒为 0）。
    /// 同一个 UUID 被重新烘过时，记录里的来源字段一个字都没变，光看 `.导入网格(id)` 分辨不出
    /// "内容换了一份"；靠它把这个事实记进几何段版本（等价于原先指纹里的 `导入网格库.版本号`）。
    var 网格库版本: UInt64

    /// 程序网格形状（导入网格时为 nil）
    var 程序网格形状: MeshKind? {
        if case .程序网格(let 形状) = 来源 { return 形状 }
        return nil
    }

    /// 导入网格标识（程序网格时为 nil）
    var 导入网格标识: UUID? {
        if case .导入网格(let 标识) = 来源 { return 标识 }
        return nil
    }
}

// MARK: - 几何接线

/// 几何接线：场景模型里"几何"进入数据层的唯一入口（规矩 1），
/// 消费端一律经 `场景快照.几何` 的只读视图取值（规矩 2）。
///
/// 它同时是几何段版本号的唯一记账方：只有它知道"这次写入到底改没改几何"，
/// 所以订阅者比的是单调版本号，而不是对整场景重算一遍几何哈希。
///
/// 记账口径（与灯光接线同构）：
/// - 逐键版本：该物体的「来源 + 导入网格内容版本」真变了才 +1；静止帧同步不推进。
/// - 内容版本：整段单调计数，任何一份几何新增 / 变化 / 消失都 +1。
final class 几何接线 {

    static let 共享 = 几何接线()

    private let 层 = 场景数据层.共享

    /// 键 → 标识 / 上次取值 / 逐键版本：三张表原先各写一遍，现在统一在 `域模版` 里。
    /// 锁实例仍由接线注入（几何是普通锁：写入只从主线程的同步进来）。
    private let 簿 = 域模版<几何域标签, 几何源取值>(锁: NSLock())

    /// 网格池那边的记账：引用数 / 两轮回收 / 回收开关 / 兜底计数。
    /// 与 `簿` 分开一把锁 —— NSLock 不可重入，混用会在"拿簿的同时摸网格账"处自锁。
    private let 辅助锁 = NSLock()
    /// 导入网格 → 当前有多少个几何记录指着它。
    /// 几何域只管"来源指向谁"，这本账就是域对网格池的引用计数。
    private var 网格引用数: [UUID: Int] = [:]

    /// 连续两轮同步都没人引用的网格才真正放掉。
    /// 项目加载是"先清空 objects 再填"，一轮就删会把整池抹平，所以故意要两轮确认。
    private var 待回收: [UUID: UInt8] = [:]

    /// 回收轮询的时间节流：同步可能被拖拽滑块一秒叫上百次，
    /// 不节流会把"两轮确认"压缩到几毫秒内，加载过渡态照样会被误删。
    private var 上次轮询: TimeInterval = 0

    /// 项目切换是"整池替换 + Store 重新载入"的过渡态，中间的引用关系对不上，
    /// 这段时间必须停掉回收，否则新池里的几何会被当成垃圾删掉。
    private var 回收暂停 = false

    /// 整段内容版本（诊断与"有没有人动几何"的粗判）：真身在 `簿`，这里只做转发。
    var 内容版本: UInt64 { 簿.内容版本 }
    /// 本轮同步进来的键序：决定几何段的装配顺序（必须与模型顺序一致，
    /// 否则三角形下标全变，画面不再逐像素等价）。
    var 当前键序: [String] { 簿.键序快照() }

    var 同步次数: UInt64 { 簿.同步次数 }
    var 实际写入次数: UInt64 { 簿.实际写入次数 }

    private init() {}

    // MARK: 写入（唯一写入方）

    /// 把模型里的几何同步进几何域，返回"带几何记账"的快照。
    /// - Parameter 列表: 已按"可见 + 非灯"筛过的几何源（顺序即模型顺序）。
    @discardableResult
    func 同步(_ 列表: [几何源取值]) -> 场景快照 {
        var 新键序: [String] = []
        新键序.reserveCapacity(列表.count)

        for 几何 in 列表 {
            新键序.append(几何.外部键)

            let 旧id = 簿.标识(键: 几何.外部键)
            let 旧取值 = 簿.值(键: 几何.外部键)

            var 几何id = 旧id
            if let id = 旧id {
                // 记录还在：只有来源 / 名称真的变了才写域。
                // 取不到记录（已被回收）不补建、不重试 —— 规矩 3：断言 + 日志，不当场重建。
                if let 旧记录 = 层.几何.取(id) {
                    if 旧记录.来源 != 几何.来源 || 旧记录.名称 != 几何.名称 {
                        _ = 层.几何.改(id, 令牌: .几何) { 记录 in
                            记录.名称 = 几何.名称
                            记录.来源 = 几何.来源
                        }
                        簿.计一次写入()
                    }
                }
            } else {
                let 记录 = 几何记录(名称: 几何.名称, 来源: 几何.来源)
                if let 新id = 层.几何.新增(记录, 令牌: .几何) {
                    几何id = 新id
                    簿.计一次写入()
                }
            }

            // 逐键版本：来源（程序网格形状 / 导入网格 UUID）或导入网格内容版本变了才推进。
            // 口径与灯光接线的"参数版本"一致：只有真正影响成像的字段才推进版本，
            // 光改名字不该让几何段重建一次。
            let 版本该推进 = 旧取值?.来源 != 几何.来源 || 旧取值?.网格库版本 != 几何.网格库版本
            簿.记入(键: 几何.外部键, 标识: 几何id, 值: 几何, 版本该推进: 版本该推进)
        }

        // 物体被删 / 被隐藏：登记删除（物理回收交给引用计数轮询，规矩 5）。
        // 这里只交回 id，不自己判定"GPU 还用不用"。
        let 消失的键 = 簿.收尾(键序: 新键序)
        if !消失的键.isEmpty {
            for 键 in 消失的键 {
                if let id = 簿.移除(键: 键) { _ = 层.几何.请求删除(id, 令牌: .几何) }
            }
            簿.推进内容版本()
        }

        // 引用记账 + 回收：域是唯一知道"谁指着哪块几何"的地方，回收也只能在这里判。
        轮询回收网格(对象数: 列表.count)

        var 快照 = 层.生成快照()
        快照.几何记账 = 几何版本记账(内容: 簿.内容版本)
        return 快照
    }

    /// 暂停 / 恢复回收轮询。切换项目的整段流程必须包起来，其它场合不要动。
    func 暂停回收(_ 暂停: Bool) {
        辅助锁.lock()
        回收暂停 = 暂停
        if 暂停 { 待回收.removeAll() }
        辅助锁.unlock()
    }

    /// 消费端取"程序形状"的唯一入口：域里有就按域，取不到才用调用方给的兜底。
    /// 兜底不是正常路径 —— objects 一变就会同步进域，正常永远命中；
    /// 留着它只是宁可画旧形状，也不让物体凭空消失。命中次数会记账，便于查漏。
    func 程序形状(键: String, 兜底: @autoclosure () -> MeshKind) -> MeshKind {
        if let 形状 = 取值(键: 键)?.程序网格形状 { return 形状 }
        辅助锁.lock()
        兜底命中次数 &+= 1
        辅助锁.unlock()
        return 兜底()
    }

    /// 兜底被命中过几次（正常应为 0；不为 0 说明有消费端跑在域同步之前）
    private(set) var 兜底命中次数: UInt64 = 0

    /// 某块导入网格此刻被几个几何记录引用（0 = 本轮无人引用，已进入回收倒计时）
    func 引用数(网格: UUID) -> Int {
        辅助锁.lock()
        defer { 辅助锁.unlock() }
        return 网格引用数[网格] ?? 0
    }

    /// 引用记账 + 两阶段回收。
    /// 规矩 5 说的"物理回收交给引用计数轮询"就落在这个方法里：
    /// 接线只负责判定与登记，真正的内存释放仍是 导入网格库.移除。
    private func 轮询回收网格(对象数: Int) {
        辅助锁.lock()
        let 暂停中 = 回收暂停
        辅助锁.unlock()
        guard !暂停中 else { return }

        let 现在 = Date().timeIntervalSinceReferenceDate
        辅助锁.lock()
        let 该轮询 = 现在 - 上次轮询 >= 0.5
        if 该轮询 { 上次轮询 = 现在 }
        辅助锁.unlock()
        guard 该轮询 else { return }

        var 计数: [UUID: Int] = [:]
        let 全部取值 = 簿.全部值()
        计数.reserveCapacity(全部取值.count)
        for 取值 in 全部取值.values {
            if let 标识 = 取值.导入网格标识 { 计数[标识, default: 0] += 1 }
        }
        辅助锁.lock()
        网格引用数 = 计数
        辅助锁.unlock()

        // 这一轮场景是空的：只在"确实没有物体"的新项目里成立，也可能是加载过渡态，一律不动手
        guard 对象数 > 0 else { return }

        for 标识 in 导入网格库.域内部.全部标识() {
            if 计数[标识] != nil {
                辅助锁.lock()
                待回收[标识] = nil
                辅助锁.unlock()
                continue
            }
            var 累计: UInt8
            辅助锁.lock()
            累计 = (待回收[标识] ?? 0) &+ 1
            待回收[标识] = 累计 >= 2 ? nil : 累计
            辅助锁.unlock()
            guard 累计 >= 2 else { continue }
            导入网格库.域内部.移除(标识)
            簿.推进内容版本()
        }
    }

    // MARK: 网格池门面（池是几何域的私有存储，外部一律经域访问）

    // 几何域是唯一所有者，网格池只是它落数据的地方。谁都不许绕过域直接摸池 ——
    // 下面这组方法与池同名，就是为了把散在工程里的 .shared 直连一次性改成经域调用。

    @discardableResult
    func 存入(_ 网格集: [导入网格]) -> UUID { 导入网格库.域内部.存入(网格集) }

    func 取(_ id: UUID) -> [导入网格]? { 导入网格库.域内部.取(id) }

    func 存在(_ id: UUID) -> Bool { 导入网格库.域内部.存在(id) }

    func 版本号(_ id: UUID) -> UInt64 { 导入网格库.域内部.版本号(id) }

    func 移除(_ id: UUID) { 导入网格库.域内部.移除(id) }

    func 恢复(_ 表: [UUID: [导入网格]]) { 导入网格库.域内部.恢复(表) }

    func 保留(_ ids: Set<UUID>) { 导入网格库.域内部.保留(ids) }

    func 快照() -> [UUID: [导入网格]] { 导入网格库.域内部.快照() }

    func 快照与版本() -> (池: [UUID: [导入网格]], 版本: [UUID: UInt64]) {
        导入网格库.域内部.快照与版本()
    }

    func 全部标识() -> [UUID] { 导入网格库.域内部.全部标识() }

    var 占用条目数: Int { 导入网格库.域内部.占用条目数 }

    var 总三角形数: Int { 导入网格库.域内部.总三角形数 }

    func 局部包围球(_ id: UUID) -> (中心: SIMD3<Float>, 半径: Float)? {
        导入网格库.域内部.局部包围球(id)
    }

    func 生成实体(_ id: UUID, 名称: String, 替身: [导入网格]? = nil) -> Entity? {
        导入网格库.域内部.生成实体(id, 名称: 名称, 替身: 替身)
    }

    func 转PT片段(_ id: UUID) -> [PTGeometry.Piece] { 导入网格库.域内部.转PT片段(id) }

    func 三角点列(_ id: UUID) -> [SIMD3<Float>] { 导入网格库.域内部.三角点列(id) }

    // MARK: 读取（只经快照只读视图）

    /// 从快照读出几何源（顺序 = 同步进来的模型顺序）。
    /// 只持有只读视图：这里拿不到任何写入口，规矩 2 由类型系统兜住。
    ///
    /// 注意：来源以**域记录**为准，不拿接线的缓存直接顶替 —— 否则"读域"就退化成读接线，
    /// 唯一所有者只是名义上的。
    func 取几何源(_ 快照: 场景快照) -> [几何源取值] {
        let 键序 = 簿.键序快照()
        let 缓存 = 簿.全部值()

        var 结果: [几何源取值] = []
        结果.reserveCapacity(键序.count)
        for 键 in 键序 {
            guard let id = 簿.标识(键: 键),
                let 记录 = 快照.几何.取(id),
                let 记账 = 缓存[键]
            else { continue }
            结果.append(
                几何源取值(
                    外部键: 键,
                    名称: 记录.名称,
                    来源: 记录.来源,
                    网格库版本: 记账.网格库版本
                )
            )
        }
        return 结果
    }

    /// 单个物体的几何源（转译装配时按对象取来源）。
    /// - Returns: 没登记过就是 nil，调用方自行决定回落到模型（第一次构建那一帧）。
    func 取值(键: String) -> 几何源取值? {
        let id = 簿.标识(键: 键)
        let 记账 = 簿.值(键: 键)

        guard let id, let 记录 = 层.几何.取(id) else { return nil }
        guard let 记账 else { return nil }
        return 几何源取值(
            外部键: 键,
            名称: 记录.名称,
            来源: 记录.来源,
            网格库版本: 记账.网格库版本
        )
    }

    /// 单份几何的来源（只读域记录）。
    func 来源(键: String) -> 几何来源? {
        guard let id = 簿.标识(键: 键) else { return nil }
        return 层.几何.取(id)?.来源
    }

    func 几何标识(键: String) -> 稳定标识<几何域标签>? { 簿.标识(键: 键) }

    /// 逐记录版本号：几何段缓存 / 加速结构判"这份几何动没动"用它，不再自己哈希来源。
    func 记录版本(键: String) -> UInt64 { 簿.记录版本(键: 键) }

    /// 段版本：这批键对应记录的逐键版本之和。
    /// 单调不减 —— 任何一份几何真变了，和必变；全都没变，和不变。
    /// （删记录时和会变小，所以只有"变没变"这一个信息可用，与灯光接线的灯段版本同口径。）
    func 段版本(键们: [String]) -> UInt64 { 簿.段版本(键们: 键们) }

    // MARK: 诊断

    var 记录数: Int { 层.几何.有效数量 }
}

// MARK: - 模型 → 几何源（写入方唯一入口）

extension 几何源取值 {
    /// 模型 → 几何源。只筛"可见 + 非灯"，顺序即模型顺序（决定顶点装配顺序）。
    /// 这是全工程唯一一处直接从场景模型读几何的地方：它服务于写入方（几何接线），消费端不许调。
    ///
    /// 角色不排除：角色/关节物体也有自己的几何（多为导入网格），几何域不该把它们丢掉；
    /// 某个消费端不想装配角色时，按自己的遍历条件筛键序即可（段版本按传进来的键算）。
    static func 从模型(_ objects: [SceneObject]) -> [几何源取值] {
        var 结果: [几何源取值] = []
        结果.reserveCapacity(objects.count)
        for object in objects {
            // 灯不产几何（规矩 3：灯 ↔ 几何 0:N），绝不进几何域。
            // 不按可见性筛：视口要按"隐藏物体再显示"重建，PT 段版本按自己的可见键取，
            // 若写入方先替消费端筛一遍，隐藏时记录会被删、显示时又新建，白白抖动版本。
            guard !object.是灯 else { continue }
            let 来源: 几何来源
            var 网格库版本: UInt64 = 0
            if let 网格ID = object.导入网格ID, 导入网格库.域内部.存在(网格ID) {
                来源 = .导入网格(网格ID)
                网格库版本 = 导入网格库.域内部.版本号(网格ID)
            } else {
                来源 = .程序网格(object.mesh)
            }
            结果.append(
                几何源取值(
                    外部键: object.id.uuidString,
                    名称: object.name,
                    来源: 来源,
                    网格库版本: 网格库版本
                )
            )
        }
        return 结果
    }
}
