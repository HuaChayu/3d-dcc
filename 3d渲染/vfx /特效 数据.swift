        return 见过
    }

    // MARK: 造物体

    /// 点预设 → 当场造一个发射器对象进场景。
    /// 发射器是普通场景对象：能被选中 / 移动 / 打关键帧 / 存盘，多开互不干扰。
    /// 位置沿用添加物体那套口径：排在已有对象右侧，不叠在原点。
    static func 造物体(_ 预设: 特效预设, 已有: [SceneObject]) -> SceneObject {
        let 右缘 = 已有.compactMap { 物 -> Double? in
            Double(物.position.x) + 0.9 * abs(Double(物.scale.x))
        }.max() ?? 0
        let x = 已有.isEmpty ? 0 : 右缘 + 0.9
        return SceneObject(
            name: 唯一名(预设.名称, 已有: 已有),
            mesh: .torus,               // 占位：真表示由 MTK 视口层画，出图不参与
            导入符号: 预设.符号,
            position: Vec3(x, 0.5, 0),
            scale: Vec3.uniform(0.35),
            特效: 预设.设置
        )
    }

    /// 同名对象加序号，跟添加物体同一口径
    private static func 唯一名(_ 基: String, 已有: [SceneObject]) -> String {
        let 已有名 = Set(已有.map(\.name))
        guard 已有名.contains(基) else { return 基 }
        var i = 2
        while 已有名.contains("\(基) \(i)") { i += 1 }
        return "\(基) \(i)"
    }
