import Foundation

// MARK: - 特效（粒子 / 火 / 烟 / 水）
//
// 口径：
// - 特效的「本体」是一个场景对象里的一个 `特效设置`（发射器），发射器可以有任意多个，
//   跟物体一样能被选中、移动、旋转、打关键帧、随工程存盘；
// - 这里只放「描述」，不放模拟。模拟在 MTK 视口层按设置现算（GPU compute ping-pong），
//   视口只做简单表示，路径追踪出图暂不参与；
// - 全局的力（风 / 重力 / 流）不在这里，它是全局单体，见 物理域。
//
// 参数口径尽量写成"美术一眼懂"的量：个/秒、秒、米/秒、度。

/// 一种特效的品类。品类决定视口用哪条模拟链路，字段本身是共用的。
enum 特效种类: String, Codable, CaseIterable, Identifiable, Sendable {
    case 粒子
    case 火
    case 烟
    case 水

    var id: String { rawValue }

    var 名称: String {
        switch self {
        case .粒子: "粒子"
        case .火:   "火"
        case .烟:   "烟"
        case .水:   "水"
        }
    }

    var 符号: String {
        switch self {
        case .粒子: "sparkles"
        case .火:   "flame.fill"
        case .烟:   "smoke.fill"
        case .水:   "drop.fill"
        }
    }

    /// 视口里的默认模拟上限：水是 PBF 粒子，比烟火的球 impostor 贵，默认给低一档
    var 默认最大粒子数: Int {
        switch self {
        case .粒子: 60000
        case .火:   50000
        case .烟:   40000
        case .水:   30000
        }
    }
}

/// 一个发射器的全部参数。作为场景对象的一部分，随对象一起存盘与打关键帧。
struct 特效设置: Codable, Equatable, Sendable {
    var 种类: 特效种类 = .粒子
    /// 关掉只是不发射，参数还在（跟灯的「启用」同语义，不删对象）
    var 启用: Bool = true
    /// 每秒发射个数
    var 发射率: Double = 3000
    /// 单个粒子存活时间（秒）
    var 寿命: Double = 1.6
    /// 初速（米/秒），沿对象自身 +Y 方向射出
    var 初速: Double = 2.0
    /// 初速随机量（0…1，按初速的比例）
    var 速度随机: Double = 0.3
    /// 扩散锥半角（度）：0 = 笔直一束，180 = 全向
    var 扩散角: Double = 18
    /// 出生尺寸 / 死亡尺寸（米）。中间按寿命线性插值
    var 起始尺寸: Double = 0.06
    var 终止尺寸: Double = 0.10
    /// 出生颜色 / 死亡颜色（线性 RGB，0…1）
    var 起始颜色: Vec3 = Vec3(1.0, 0.55, 0.15)
    var 终止颜色: Vec3 = Vec3(0.65, 0.06, 0.01)
    /// 整体不透明度（球 impostor 的 alpha 上限）
    var 不透明度: Double = 1.0
    /// 受全局重力影响的比例（0 = 完全飘着，1 = 全受）
    var 重力倍率: Double = 1.0
    /// 受全局风 / 流影响的比例
    var 风力倍率: Double = 1.0
    /// 自身湍流强度（跟全局无关的随机扰动，0…1）
    var 湍流: Double = 0.3
    /// 是否与场景做碰撞（走 SDF clipmap 的球体近似，视口层现算）
    var 碰撞: Bool = true
    /// 这个发射器最多同时在场的粒子数（性能上限，切品类时按下品类的默认值给）
    var 最大粒子数: Int = 60000
    /// 「在谁身上发射」：nil = 就用挂着这个特效的对象本身（默认，旧工程行为不变）。
    /// 指到别的物体时，四种品类一律改吃那个物体的几何 + 世界矩阵 ——
    /// 于是"想要圈圈上冒火"不必把特效挪到圈圈上，选一下发射体就行。
    var 发射体对象ID: UUID?

    // ---- 特效容器里的发射源 ----
    //
    // 这一组把发射器从"一个点/一个对象"升级成**容器**：
    // 往里面塞若干发射源（程序网格 / 导入网格 + 材质 + 自己的 TRS），
    // 合并成一份几何当发射体用。这些几何不进场景对象列表、不进大纲、视口不画，
    // 所以"想在圈上冒火"不必真摆一个看得见的圈。
    //
    // 口径：
    // - 有启用源 = 用容器自身的世界矩阵 + 合并几何（发射体对象ID 让位）；
    // - 没有启用源 = 完整回到旧行为（发射体对象ID / 自己），旧工程外观不变；
    // - 容器不是范围锁：只是选择与组织用的节点，外面的东西照样烧、照样能被撞。
    /// Optional：旧存档里没有这个键，缺了也得能正常解码
    var 发射源们: [特效发射源]?

    /// 容器里有没有正在干活的源（决定走容器几何还是老口径）
    var 是特效容器: Bool { 特效几何库.有启用源(self) }

    /// 容器里的源总数（大纲徽章、面板标题用）
    var 源数: Int { (发射源们 ?? []).count }

    // ---- 火焰外观（仅 火 走体积时生效，全是 nil = 出厂标定）----
    //
    // 这一组不是材质参数：火是自发光介质，颜色来自**温度**而不是贴图。
    // 你能调的是温度区间（芯 / 尾两端各自的色温）与"薄厚"，不是给火刷颜色。
    /// 芯色温 K：火根白热的温度。1400 = 橙红，2400 = 橙黄，3400 = 亮黄白（默认）
    var 火焰芯色温: Double?
    /// 尾色温 K：外焰与火舌顶端。600 = 暗红（默认 760），压太低整体发红发脏
    var 火焰尾色温: Double?
    /// 内部结构 0…1：0 = 均匀一块糊，0.5~0.9 = 有薄有厚、局部透局部不透（默认 0.6）
    var 火焰结构: Double?
    /// 亮度倍率：默认 1。够亮才有"里面还藏着火芯"的层次，过曝会一片死黄
    var 火焰亮度: Double?

    // ---- 流体高级调参（仅 火/烟 走体积场时生效）----
    // 一律用可选类型：nil = 用出厂标定值，旧工程存档里没有这些键也能正常解出来，
    // 且不会因为新增字段把已经调好的火/烟外观改掉。
    /// 浮力倍率（1 = 出厂）。火舌窜多高主要看它
    var 浮力倍率: Double?
    /// 源温倍率（1 = 出厂）。高温 = 更亮更冲的火芯
    var 源温倍率: Double?
    /// 密度死区倍率（1 = 出厂）。调大 = 尾雾被切得更狠、轮廓更干净
    var 死区倍率: Double?
    /// 每帧流体子步数（1…4）。越大越稳越贵
    var 子步数: Int?
    /// 压力雅可比迭代次数（8…120）。太小压力传不到域顶、浮力会被散度吃掉
    var 压力迭代: Int?

    init(种类: 特效种类 = .粒子) {
        self.种类 = 种类
        self.最大粒子数 = 种类.默认最大粒子数
    }
}

